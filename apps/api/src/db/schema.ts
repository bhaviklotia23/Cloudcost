import { sql } from 'drizzle-orm';
import {
  boolean,
  date,
  index,
  integer,
  jsonb,
  numeric,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

export const memberRole = pgEnum('member_role', ['admin', 'member']);
export const awsAccountProvider = pgEnum('aws_account_provider', ['aws', 'demo']);
export const awsAccountStatus = pgEnum('aws_account_status', ['pending', 'connected', 'error']);

const timestamps = {
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
};

export const organizations = pgTable('organizations', {
  id: uuid('id').primaryKey().defaultRandom(),
  name: text('name').notNull(),
  plan: text('plan').notNull().default('free'),
  /** Flag a project/service when week-over-week spend grows by at least this percentage... */
  anomalyThresholdPct: integer('anomaly_threshold_pct').notNull().default(30),
  /** ...and by at least this many dollars (keeps $0.40 -> $0.90 from paging anyone). */
  anomalyMinDelta: numeric('anomaly_min_delta', { precision: 12, scale: 2, mode: 'number' })
    .notNull()
    .default(10),
  digestEnabled: boolean('digest_enabled').notNull().default(true),
  ...timestamps,
});

export const users = pgTable(
  'users',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    email: text('email').notNull(),
    name: text('name').notNull(),
    passwordHash: text('password_hash').notNull(),
    ...timestamps,
  },
  (t) => [uniqueIndex('users_email_lower_idx').on(sql`lower(${t.email})`)],
);

export const orgMembers = pgTable(
  'org_members',
  {
    orgId: uuid('org_id')
      .notNull()
      .references(() => organizations.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    role: memberRole('role').notNull().default('member'),
    ...timestamps,
  },
  (t) => [primaryKey({ columns: [t.orgId, t.userId] }), index('org_members_user_idx').on(t.userId)],
);

export const invites = pgTable(
  'invites',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    orgId: uuid('org_id')
      .notNull()
      .references(() => organizations.id, { onDelete: 'cascade' }),
    email: text('email').notNull(),
    role: memberRole('role').notNull().default('member'),
    /** sha256 of the token — the raw token only ever exists in the emailed link. */
    tokenHash: text('token_hash').notNull().unique(),
    invitedBy: uuid('invited_by').references(() => users.id, { onDelete: 'set null' }),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
    acceptedAt: timestamp('accepted_at', { withTimezone: true }),
    ...timestamps,
  },
  (t) => [index('invites_org_idx').on(t.orgId)],
);

export const awsAccounts = pgTable(
  'aws_accounts',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    orgId: uuid('org_id')
      .notNull()
      .references(() => organizations.id, { onDelete: 'cascade' }),
    accountNickname: text('account_nickname').notNull(),
    provider: awsAccountProvider('provider').notNull().default('aws'),
    status: awsAccountStatus('status').notNull().default('pending'),
    /** 12-digit AWS account id, parsed from the role ARN once connected. */
    awsAccountId: text('aws_account_id'),
    roleArn: text('role_arn'),
    /** Generated by CloudCost, never chosen by the customer — prevents the confused-deputy problem. */
    externalId: text('external_id').notNull().unique(),
    costTagKey: text('cost_tag_key').notNull().default('Project'),
    lastError: text('last_error'),
    connectedAt: timestamp('connected_at', { withTimezone: true }),
    lastSyncedAt: timestamp('last_synced_at', { withTimezone: true }),
    ...timestamps,
  },
  (t) => [index('aws_accounts_org_idx').on(t.orgId)],
);

export type Breakdown = {
  byProject: Record<string, number>;
  byService: Record<string, number>;
  daily: { date: string; amount: number }[];
};

export type Anomaly = {
  dimension: 'project' | 'service' | 'total';
  key: string;
  previous: number;
  current: number;
  delta: number;
  /** null when the item is new this week (previous = 0). */
  changePct: number | null;
};

export const costSnapshots = pgTable(
  'cost_snapshots',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    awsAccountId: uuid('aws_account_id')
      .notNull()
      .references(() => awsAccounts.id, { onDelete: 'cascade' }),
    /** Monday (UTC) that starts the ISO week. */
    weekStart: date('week_start', { mode: 'string' }).notNull(),
    totalCost: numeric('total_cost', { precision: 14, scale: 4, mode: 'number' }).notNull(),
    currency: text('currency').notNull().default('USD'),
    breakdownJson: jsonb('breakdown_json').$type<Breakdown>().notNull(),
    anomalies: jsonb('anomalies').$type<Anomaly[]>().notNull().default([]),
    /** False while the week is still in progress. */
    isComplete: boolean('is_complete').notNull().default(false),
    syncedAt: timestamp('synced_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex('cost_snapshots_account_week_idx').on(t.awsAccountId, t.weekStart)],
);

export type Organization = typeof organizations.$inferSelect;
export type User = typeof users.$inferSelect;
export type OrgMember = typeof orgMembers.$inferSelect;
export type Invite = typeof invites.$inferSelect;
export type AwsAccount = typeof awsAccounts.$inferSelect;
export type CostSnapshot = typeof costSnapshots.$inferSelect;
export type Role = (typeof memberRole.enumValues)[number];
